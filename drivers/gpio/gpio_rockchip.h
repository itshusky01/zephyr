#ifndef ZEPHYR_DRIVERS_GPIO_GPIO_ROCKCHIP_H_
#define ZEPHYR_DRIVERS_GPIO_GPIO_ROCKCHIP_H_

#include <stdint.h>

/* Legacy Rockchip GPIO layout. */
#define RK_GPIO_LEGACY_OUTPUT_REG    0x0000U
#define RK_GPIO_LEGACY_DIRECTION_REG 0x0004U
#define RK_GPIO_LEGACY_EXT_PORT_REG  0x0050U
#define RK_GPIO_LEGACY_IRQ_EN_REG    0x0030U
#define RK_GPIO_LEGACY_IRQ_MASK_REG  0x0034U
#define RK_GPIO_LEGACY_IRQ_EDGE_REG  0x0038U
#define RK_GPIO_LEGACY_IRQ_POL_REG   0x003cU
#define RK_GPIO_LEGACY_IRQ_STAT_REG  0x0040U
#define RK_GPIO_LEGACY_IRQ_ACK_REG   0x004cU

/* Split-register Rockchip GPIO layout. */
#define RK_GPIO_SPLIT_OUTPUT_REG    0x0000U
#define RK_GPIO_SPLIT_DIRECTION_REG 0x0008U
#define RK_GPIO_SPLIT_IRQ_EN_REG    0x0010U
#define RK_GPIO_SPLIT_IRQ_MASK_REG  0x0018U
#define RK_GPIO_SPLIT_IRQ_EDGE_REG  0x0020U
#define RK_GPIO_SPLIT_IRQ_POL_REG   0x0028U
#define RK_GPIO_SPLIT_IRQ_BOTH_REG  0x0030U
#define RK_GPIO_SPLIT_IRQ_STAT_REG  0x0050U
#define RK_GPIO_SPLIT_IRQ_ACK_REG   0x0060U
#define RK_GPIO_SPLIT_EXT_PORT_REG  0x0070U
#define RK_GPIO_VERSION_REG         0x0078U

#define RK_GPIO_BANK_PINS       32U
#define RK_GPIO_BANK4_SWAP_PINS 6U

/* Values read from RK_GPIO_VERSION_REG. */
#define RK_GPIO_VERSION_LEGACY 0x00000000U
#define RK_GPIO_VERSION_V2     0x01000c2bU
#define RK_GPIO_VERSION_V2_1   0x0101157cU
#define RK_GPIO_VERSION_V2_2   0x010219c8U
#define RK_GPIO_VERSION_V2_6   0x01063f6eU

#endif /* ZEPHYR_DRIVERS_GPIO_GPIO_ROCKCHIP_H_ */
